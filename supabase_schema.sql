-- 4. Enable Row Level Security (RLS) with Public Access (Ideal for personal hobby projects)
ALTER TABLE public.shelves ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access on shelves" ON public.shelves FOR SELECT USING (true);
CREATE POLICY "Allow public insert on shelves" ON public.shelves FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update on shelves" ON public.shelves FOR UPDATE USING (true);
CREATE POLICY "Allow public delete on shelves" ON public.shelves FOR DELETE USING (true);

CREATE POLICY "Allow public read access on books" ON public.books FOR SELECT USING (true);
CREATE POLICY "Allow public insert on books" ON public.books FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update on books" ON public.books FOR UPDATE USING (true);
CREATE POLICY "Allow public delete on books" ON public.books FOR DELETE USING (true);

-- 5. Create Storage Bucket for Digital Book Files
INSERT INTO storage.buckets (id, name, public) 
VALUES ('books', 'books', true)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Allow public read of books storage" ON storage.objects FOR SELECT USING (bucket_id = 'books');
CREATE POLICY "Allow public upload to books storage" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'books');
CREATE POLICY "Allow public update of books storage" ON storage.objects FOR UPDATE USING (bucket_id = 'books');
CREATE POLICY "Allow public delete of books storage" ON storage.objects FOR DELETE USING (bucket_id = 'books');
